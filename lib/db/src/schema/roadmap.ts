import { pgTable, text, varchar, integer, serial } from "drizzle-orm/pg-core";

export const roadmapRequirementsTable = pgTable("roadmap_requirements", {
  id: serial("id").primaryKey(),
  name: varchar("name", { length: 255 }).notNull(),
  category: varchar("category", { length: 50 }).notNull(),
  description: text("description").notNull(),
  dueDate: varchar("due_date", { length: 10 }).notNull(),
  status: varchar("status", { length: 30 }).notNull(),
  ibmWorkstream: varchar("ibm_workstream", { length: 100 }).notNull(),
  owner: varchar("owner", { length: 100 }).notNull(),
  priority: varchar("priority", { length: 10 }).notNull(),
});

export const roadmapRisksTable = pgTable("roadmap_risks", {
  id: serial("id").primaryKey(),
  title: varchar("title", { length: 255 }).notNull(),
  category: varchar("category", { length: 50 }).notNull(),
  likelihood: varchar("likelihood", { length: 10 }).notNull(),
  impact: varchar("impact", { length: 10 }).notNull(),
  rating: varchar("rating", { length: 10 }).notNull(),
  owner: varchar("owner", { length: 100 }).notNull(),
  mitigationAction: text("mitigation_action").notNull(),
  status: varchar("status", { length: 20 }).notNull(),
  raisedDate: varchar("raised_date", { length: 10 }).notNull(),
  notes: text("notes").notNull().default(""),
});

export const roadmapInitiativesTable = pgTable("roadmap_initiatives", {
  id: serial("id").primaryKey(),
  portfolio: varchar("portfolio", { length: 100 }).notNull(),
  product: varchar("product", { length: 100 }).notNull(),
  application: varchar("application", { length: 255 }).notNull(),
  initiativeType: varchar("initiative_type", { length: 50 }).notNull(),
  description: text("description").notNull(),
  expectedOutcome: text("expected_outcome").notNull(),
  technology: varchar("technology", { length: 100 }).notNull(),
  currentVersion: varchar("current_version", { length: 50 }).notNull().default(""),
  upgradeVersion: varchar("upgrade_version", { length: 50 }).notNull().default(""),
  jiraId: varchar("jira_id", { length: 20 }).notNull().unique(),
  serviceCategory: varchar("service_category", { length: 100 }).notNull(),
  startDate: varchar("start_date", { length: 10 }).notNull(),
  endDate: varchar("end_date", { length: 10 }).notNull(),
  status: varchar("status", { length: 30 }).notNull(),
  priority: varchar("priority", { length: 20 }).notNull(),
  notes: text("notes").notNull().default(""),
  domain: varchar("domain", { length: 100 }).notNull().default(""),
  planYear: integer("plan_year").notNull().default(1),
  planQuarter: varchar("plan_quarter", { length: 5 }).notNull().default("Q1"),
  complexity: varchar("complexity", { length: 10 }).notNull().default("Med"),
  businessImpact: text("business_impact").notNull().default(""),
  dependency: text("dependency").notNull().default(""),
  tShirtSize: varchar("tshirt_size", { length: 4 }).notNull().default(""),
  tShirtRationale: text("tshirt_rationale").notNull().default(""),
  roiPlan: text("roi_plan").notNull().default(""),
});
